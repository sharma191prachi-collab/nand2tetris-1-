// Box.asm - K=53: row 53, 20 rows tall,
(MAIN)
    @KBD
    D=M
    @BLACK
    D;JNE
    @color
    M=0
    @DRAW
    0;JMP
(BLACK)
    @color
    M=-1
(DRAW)
    @18080          // 16384 + 32*53
    D=A
    @addr
    M=D
    @20
    D=A
    @rows
    M=D
(ROWLOOP)
    @2              // (53 mod 4) + 1
    D=A
    @cols
    M=D
    @addr
    D=M
    @p
    M=D
(COLLOOP)
    @color
    D=M
    @p
    A=M
    M=D
    @p
    M=M+1
    @cols
    M=M-1
    D=M
    @COLLOOP
    D;JGT
    @addr
    D=M
    @32
    D=D+A
    @addr
    M=D
    @rows
    M=M-1
    D=M
    @ROWLOOP
    D;JGT
    @MAIN
    0;JMP
